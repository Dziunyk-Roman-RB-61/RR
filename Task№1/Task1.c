#include <stdio.h> 
// оголошення функції, яка очищує буфер вводу від некоректних символів (прототип функції)
void clearInputBuffer(void);

// оголошення функції, яка обчислює суму ряду за заданими значеннями a та N (прототип функції)
double calculateSeriesSum(double a, int N);

// головна функція програми, з якої починається виконання програми
int main(void)
{
    double a = 0.0; // оголошення змінної типу double (з плаваючою комою подвійної точності) для параметра a, ініціалізація нулем
    int N = 0;      // оголошення змінної типу int (знакове ціле число) для верхньої межі сумування N, ініціалізація нулем
    double S = 0.0; // оголошення змінної типу double (з плаваючою комою подвійної точності) для результату суми ряду S

    // цикл із постумовою: повторюється, доки користувач не введе коректне значення параметра a
    do
    {
        printf("Enter the value of variable a (a >= 0): "); // виведення на екран запрошення до введення параметра a

        // перевірка результату scanf: якщо не вдалося зчитати рівно одне дійсне число, то введення некоректне
        if (scanf("%lf", &a) != 1)
        {
            printf("Error: a number is required.\n"); // повідомлення про некоректний формат введених даних
            clearInputBuffer();                          // видалення з буфера вводу всіх символів до кінця рядка
            a = -1.0;                                    // присвоєння недопустимого значення, щоб цикл виконався повторно
        }
        else if (a < 0.0) // перевірка умови задачі: параметр a не може бути від'ємним
        {
            printf("Error: the value of a must be non-negative.\n"); // повідомлення про порушення умови a >= 0
        }
    } while (a < 0.0); // умова продовження циклу: повторне введення, доки a від'ємне

    // цикл із постумовою: повторюється, доки користувач не введе коректне значення параметра N
    do
    {
        printf("Enter an integer N (N >= 1): "); // виведення на екран запрошення до введення параметра N

        // перевірка результату scanf: якщо не вдалося зчитати ціле число, то введення некоректне
        if (scanf("%d", &N) != 1)
        {
            printf("Error: an integer is required.\n"); // повідомлення про некоректний формат введених даних
            clearInputBuffer();                               // видалення з буфера вводу всіх символів до кінця рядка
            N = 0;                                            // присвоєння недопустимого значення, щоб цикл виконався повторно
        }
        else if (N < 1) // перевірка умови задачі: верхня межа сумування N має бути не меншою за 1
        {
            printf("Error: the value of N must be at least 1.\n"); // повідомлення про порушення умови N >= 1
        }
    } while (N < 1); // умова продовження циклу: повторне введення, доки N менше за одиницю

    S = calculateSeriesSum(a, N); // виклик функції обчислення суми ряду, результат записується у змінну S

    printf("a = %.4f, N = %d\n", a, N); // виведення на екран введених початкових даних із чотирма знаками після коми
    printf("Series sum S = %.10f\n", S); // виведення на екран результату обчислення з десятьма знаками після коми

    return 0; // повернення коду 0 операційній системі, що означає успішне завершення програми
}

// визначення функції очищення буфера вводу, функція не приймає параметрів і не повертає значення
void clearInputBuffer(void)
{
    int ch = 0; // оголошення змінної типу int для зберігання поточного прочитаного символу

    // цикл зчитує символи по одному, доки не буде досягнуто кінець рядка або кінець файлу
    while ((ch = getchar()) != '\n' && ch != EOF)
    {
        // тіло циклу порожнє: усі прочитані символи відкидаються
    }
}

// визначення функції обчислення суми ряду, приймає параметр a та верхню межу N за значенням
double calculateSeriesSum(double a, int N)
{
    double sum = 1.0;   // оголошення змінної для суми, початкове значення 1 відповідає доданку "1" у формулі ряду
    double power = 1.0; // оголошення змінної для поточного степеня a^n, початкове значення a^0 = 1

    // цикл з лічильником: перебір усіх номерів членів ряду від n = 1 до n = N включно
    for (int n = 1; n <= N; n++)
    {
        power = power * a; // отримання наступного степеня a^n множенням попереднього степеня a^(n-1) на a (без функції pow)

        sum = sum + power / (a + (double)n); // додавання до суми n-го члена ряду; явне перетворення n до double для дійсного ділення
    }

    return sum; 
}